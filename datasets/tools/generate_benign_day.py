#!/usr/bin/env python3
"""Generates datasets/_shared/benign-normal-day.log: one ordinary day on a small Ubuntu server.

Deterministic (fixed seed): `python3 datasets/tools/generate_benign_day.py` prints the file, and a
test checks the committed file is exactly this output. The traffic is realistic on purpose:
key-based logins, a few password typos followed by a success, cron and systemd-logind noise, sudo
for routine administration, and background probes from the Internet that stay below every
threshold. NO rule may alert on it. Addresses come from the documentation ranges (RFC 5737).
"""

import random
from datetime import UTC, datetime, timedelta

SEED = 20260925
HOST = "prod-web-01"
DAY = datetime(2026, 9, 24, tzinfo=UTC)
USERS = {"alice": "10.0.0.5", "bob": "10.0.0.6", "carol": "10.0.0.7", "deploy": "10.0.0.20"}
PROBE_NETS = ("198.51.100", "203.0.113", "192.0.2")
PROBE_NAMES = ("admin", "test", "ubuntu", "oracle", "git", "pi", "user", "guest")
COMMANDS = (
    "/usr/bin/apt-get update",
    "/usr/bin/systemctl status nginx",
    "/usr/bin/journalctl -u nginx",
    "/usr/bin/systemctl reload nginx",
    "/usr/bin/tail -n 100 /var/log/nginx/error.log",
)
HEADER = """\
# expect: 0
# description: An ordinary day on a small server (~2000 lines): logins, cron, sudo, typos, probes below every threshold. No rule may alert.
# Generated by datasets/tools/generate_benign_day.py (fixed seed): do not edit by hand.
"""


def generate() -> str:
    rng = random.Random(SEED)
    pid = 1000
    entries: list[tuple[datetime, str]] = []

    def emit(at: datetime, process: str, message: str, with_pid: bool = True) -> None:
        nonlocal pid
        pid += rng.randint(1, 7)
        tag = f"{process}[{pid}]" if with_pid else process
        stamp = at.strftime("%Y-%m-%dT%H:%M:%S.") + f"{at.microsecond:06d}+00:00"
        entries.append((at, f"{stamp} {HOST} {tag}: {message}"))

    def at(hour: int) -> datetime:
        return DAY + timedelta(hours=hour, seconds=rng.uniform(0, 3599))

    for hour in range(24):
        emit(DAY + timedelta(hours=hour, minutes=17), "CRON", "pam_unix(cron:session): session opened for user root(uid=0) by (uid=0)")
        emit(DAY + timedelta(hours=hour, minutes=17, seconds=1), "CRON", "pam_unix(cron:session): session closed for user root")

        low, high = (9, 16) if 8 <= hour <= 19 else (2, 5)  # more sessions during working hours
        for _ in range(rng.randint(low, high)):
            user = rng.choice(list(USERS))
            ip, port, start = USERS[user], rng.randint(40000, 60000), at(hour)
            if rng.random() < 0.15:  # a typo or two, then the right password
                for i in range(rng.randint(1, 2)):
                    emit(start + timedelta(seconds=i * 3), "sshd", f"Failed password for {user} from {ip} port {port} ssh2")
                start += timedelta(seconds=8)
                emit(start, "sshd", f"Accepted password for {user} from {ip} port {port} ssh2")
            else:
                key = "".join(rng.choice("ABCDEFabcdef0123456789+") for _ in range(43))
                emit(start, "sshd", f"Accepted publickey for {user} from {ip} port {port} ssh2: ED25519 SHA256:{key}")
            emit(start, "sshd", f"pam_unix(sshd:session): session opened for user {user}(uid=1001) by (uid=0)")
            emit(start, "systemd-logind", f"New session {rng.randint(1, 900)} of user {user}.", with_pid=True)
            end = start + timedelta(seconds=rng.randint(60, 2400))
            for command in rng.sample(COMMANDS, rng.randint(0, 3)):
                when = start + (end - start) * rng.random()
                emit(when, "sudo", f"{user} : TTY=pts/0 ; PWD=/home/{user} ; USER=root ; COMMAND={command}", with_pid=False)
                emit(when, "sudo", f"pam_unix(sudo:session): session opened for user root(uid=0) by {user}(uid=1001)", with_pid=False)
            emit(end, "sshd", f"Received disconnect from {ip} port {port}:11: disconnected by user")
            emit(end, "sshd", f"Disconnected from user {user} {ip} port {port}")
            emit(end, "sshd", f"pam_unix(sshd:session): session closed for user {user}")

        for _ in range(rng.randint(0, 2)):  # Internet background noise: 1-2 attempts, far below any threshold
            ip = f"{rng.choice(PROBE_NETS)}.{rng.randint(1, 254)}"
            port, name, start = rng.randint(1024, 65000), rng.choice(PROBE_NAMES), at(hour)
            emit(start, "sshd", f"Invalid user {name} from {ip} port {port}")
            for i in range(rng.randint(1, 2)):
                emit(start + timedelta(seconds=1 + 3 * i), "sshd", f"Failed password for invalid user {name} from {ip} port {port} ssh2")
            emit(start + timedelta(seconds=8), "sshd", f"Connection closed by invalid user {name} {ip} port {port} [preauth]")

    entries.sort(key=lambda entry: entry[0])
    return HEADER + "\n".join(line for _, line in entries) + "\n"


if __name__ == "__main__":
    print(generate(), end="")
